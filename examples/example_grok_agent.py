async def main() -> None:
    parser = argparse.ArgumentParser(
        description="P-MCP + Grok (xAI) Agent Example",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Run without real Grok API key (simulated plan)",
    )
    parser.add_argument(
        "--server", metavar="URL", default=None,
        help="Connect to a remote P-MCP HTTP server (e.g. http://localhost:8081)",
    )
    parser.add_argument(
        "--demo",
        choices=["pick", "safety", "sensors", "all"],
        default="all",
        help="Which demo to run (default: all)",
    )
    args = parser.parse_args()

    if not args.dry_run and not os.environ.get("XAI_API_KEY"):
        print(
            "\n  NOTE: XAI_API_KEY not set — running in dry-run mode.\n"
            "        Set export XAI_API_KEY=xai-... for real Grok responses.\n"
        )
        args.dry_run = True

    demos = args.demo if args.demo != "all" else ["pick", "safety", "sensors"]
    if isinstance(demos, str):
        demos = [demos]

    for demo_name in demos:
        if demo_name == "pick":
            await demo_pick_and_place(args.dry_run, args.server)
        elif demo_name == "safety":
            await demo_safety_rejection(args.dry_run)
        elif demo_name == "sensors":
            await demo_sensor_read(args.dry_run)


if __name__ == "__main__":
    asyncio.run(main())
