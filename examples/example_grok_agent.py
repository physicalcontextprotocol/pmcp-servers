"""
P-MCP + Grok (xAI) Agent Example
==================================
Demonstrates Grok commanding a physical robot arm through P-MCP with
full shadow-validated safety — no hardware required to run this demo.

Architecture:
    Grok LLM (xAI API)
         │  tool_use (OpenAI-compatible)
         ▼
    GrokAgent  ← this file
         │  discover tools (actuations/list)
         │  shadow preview before any call
         │  call actuation (tools/call)
         ▼
    PMCPServer (in-process, simulated UR5e arm)
         │  Constitution → Shadow → TEE Gate
         ▼
    Simulated hardware (no real robot needed)

Usage:
    # With real xAI Grok API:
    export XAI_API_KEY=xai-...
    python examples/example_grok_agent.py

    # Without API key (dry-run, shows what Grok WOULD do):
    python examples/example_grok_agent.py --dry-run

    # Target a remote P-MCP server over HTTP:
    python examples/example_grok_agent.py --server http://my-robot:8081

Requirements:
    pip install openai          # xAI uses the OpenAI-compatible SDK
    pip install cryptography    # for TEE / safety constitution
"""
