async def demo_pick_and_place(dry_run: bool, server_url: Optional[str]) -> None:
    """
    Demo 1: Grok plans a pick-and-place and P-MCP validates safety.
    """
    grok   = GrokClient(model="grok-3")
    server = None if server_url else build_arm_server("ur5e-demo", "UR5e", "cell-A")

    agent = GrokAgent(grok=grok, server=server, server_url=server_url)
    await agent.run_mission(
        "Pick the red box at position (0.4, 0.0, 0.12) "
        "and place it at (-0.3, 0.3, 0.12). "
        "Go home after."
    )


async def demo_safety_rejection(dry_run: bool) -> None:
    """
    Demo 2: Grok tries to command an unsafe move; shadow preview blocks it.
    Shadow validator rejects Z < floor (negative Z = below ground).
    """
    grok   = GrokClient(model="grok-3")
    server = build_arm_server("ur5e-safety-test", "UR5e", "cell-B")

    print(f"\n{'═'*70}")
    print(f"  SAFETY DEMO: Attempting unsafe move (Z below floor)")
    print(f"{'═'*70}")

    async with PMCPClient("grok-safety-test") as client:
        await client.connect_server(server)

        unsafe_args = {"x": 0.5, "y": 0.0, "z": -0.15, "speed": 2.0}  # Z < 0 → blocked
        print(f"\n  Calling move_to({unsafe_args}) ...")

        try:
            preview = await client.shadow_preview("move_to", unsafe_args)
            if not preview.get("safe", True):
                print(f"  ✓ Shadow CORRECTLY BLOCKED: {preview.get('reason')}")
            else:
                # Try executing — constitution will block at the gate
                result = await client.call_tool("move_to", unsafe_args)
                print(f"  Result: {result}")
        except PMCPClientError as e:
            print(f"  ✓ P-MCP CORRECTLY REJECTED [{e.code}]: {e}")


async def demo_sensor_read(dry_run: bool) -> None:
    """
    Demo 3: Grok reads sensor data before planning.
    Shows how LLMs can query robot state via MCP Resources.
    """
    grok   = GrokClient(model="grok-3")
    server = build_arm_server("ur5e-sensor-demo", "UR5e", "cell-C")

    print(f"\n{'═'*70}")
    print(f"  SENSOR DEMO: Grok reads robot state before planning")
    print(f"{'═'*70}")

    async with PMCPClient("grok-sensor-test") as client:
        await client.connect_server(server)

        sensors = await client.list_sensors()
        print(f"\n  Available sensors: {[s['name'] for s in sensors]}")

        for sensor in sensors[:3]:  # read first 3 sensors
            try:
                reading = await client.read_sensor(sensor["name"])
                print(f"  {sensor['name']:30s} = {reading.get('value')} "
                      f"[{reading.get('unit', '')}]")
            except PMCPClientError as e:
                print(f"  {sensor['name']:30s}   (unavailable: {e})")

        # Now plan with sensor context
        print(f"\n  Grok plans based on current sensor state...")
        tools = await client.list_tools()
        plan  = await grok.plan(
            "The robot is at home. Move to (0.3, 0.1, 0.4) and read joint angles.",
            tools,
        )
        print(f"  Grok's {len(plan)}-step plan: "
              f"{[c['name'] for c in plan]}")


